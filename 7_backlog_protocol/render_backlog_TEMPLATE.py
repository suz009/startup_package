REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "0_context" / "protocol" / "backlog.json"
TARGET = REPO / "0_context" / "protocol" / "BACKLOG.md"
HTML_TARGET = REPO / "0_context" / "protocol" / "BACKLOG.html"

PRIORITY_ORDER = ["now", "mvp", "post_mvp", "someday"]
PRIORITY_LABEL = {
    "now": "Now — blocking or waiting on someone",
    "mvp": "MVP — needed before the project's first real use on real data",
    "post_mvp": "Post-MVP — wanted, scheduled after MVP",
    "someday": "Someday — good idea, no committed timeline",
}
STATUS_ICON = {
    "open": "⬜",
    "in_progress": "🔄",
    "done": "✅",
    "dropped": "🚫",
}
# `period_work`: whether Claude can do the task unsupervised during a period of
# work (Feature 8, the Period Work Protocol). Unset means not yet rated.
PERIOD_WORK_LABEL = {
    "yes": "yes — clear, verifiable, no user decisions expected",
    "maybe": "maybe — can progress alone, but likely stops at a judgment call",
    "no": "no — needs the user, external action, or sensitive judgment",
}

# Display names for the `area` values. REPLACE THESE with your project's own —
# they must match the vocabulary in BACKLOG_PROTOCOL.md. An area used in
# backlog.json but missing here still renders; it just shows its raw value.
AREA_LABEL = {
    "data": "Data",
    "analysis": "Analysis",
    "interface": "Interface",
    "schema": "Schema",
    "ops": "Operations",
    "docs": "Documentation",
    "protocol": "Protocol",
    "legal": "Legal",
}


def render(data: dict) -> str:
    tasks = data["tasks"]
    meta = data["metadata"]
    open_tasks = [t for t in tasks if t["status"] in ("open", "in_progress")]
    closed_tasks = [t for t in tasks if t["status"] in ("done", "dropped")]

    out: list[str] = []
    add = out.append

    add("# [PROJECT_NAME] — Backlog")
    add("")
    add("**GENERATED FILE — do not edit.** Regenerate with `python3 scripts/render_backlog.py`.")
    add("The canonical source is `0_context/protocol/backlog.json`.")
    add(f"Protocol: `{meta['protocol']}`. Last updated: **{meta['last_updated']}**.")
    add("")
    add(f"**{len(open_tasks)} open**, {len(closed_tasks)} closed, {len(tasks)} total.")
    add("")
    add("---")
    add("")

    for priority in PRIORITY_ORDER:
        group = [t for t in open_tasks if t["priority"] == priority]
        if not group:
            continue
        add(f"## {PRIORITY_LABEL[priority]}")
        add("")
        for t in sorted(group, key=lambda x: x["id"]):
            icon = STATUS_ICON.get(t["status"], "⬜")
            area = AREA_LABEL.get(t["area"], t["area"])
            add(f"### {icon} {t['id']} — {t['title']}")
            add("")
            period = t.get("period_work")
            period = f" · period work: {period}" if period else ""
            add(f"*{area} · raised {t['raised']} by {t['raised_by']}{period}*")
            add("")
            # `scale: epic` marks a task too large to pick up as written, which
            # must be broken into phases and subtasks before any of it is built
            # (from OpenQuali, 2026-09-23). Shown here rather than buried in the
            # JSON, because it has to be seen when somebody chooses what to work on.
            if t.get("scale") == "epic":
                add("> **EPIC — break into phases and subtasks before starting.** "
                    "Too large to pick up as written.")
                add("")
            add(t["description"])
            add("")
            if t.get("blocked_by"):
                add(f"**Blocked by:** {t['blocked_by']}")
                add("")
            refs = t.get("related") or []
            if refs:
                add(f"**Related:** {', '.join(refs)}")
                add("")
            add(f"<sub>Raised in `{t['raised_in']}`</sub>")
            add("")
        add("---")
        add("")

    if closed_tasks:
        add("## Closed")
        add("")
        add("| ID | Title | Status | Closed | Resolution |")
        add("|---|---|---|---|---|")
        for t in sorted(closed_tasks, key=lambda x: x["id"]):
            icon = STATUS_ICON.get(t["status"], "")
            res = (t.get("resolution") or "").replace("|", "\\|")
            add(f"| {t['id']} | {t['title']} | {icon} {t['status']} | {t.get('closed') or ''} | {res} |")
        add("")

    return "\n".join(out) + "\n"


