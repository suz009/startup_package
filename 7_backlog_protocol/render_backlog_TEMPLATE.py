def render_html(data: dict) -> str:
    """One self-contained page: the whole backlog, sortable and filterable.

    The JSON is embedded rather than fetched, because this file is opened from
    disk and a browser refuses to fetch a local file from another local file. It
    is regenerated whenever `backlog.json` is committed, so the copy is never the
    stale one — see the pre-commit hook.
    """
    tasks = data["tasks"]
    meta = data["metadata"]
    counts = {}
    for task in tasks:
        counts[task["status"]] = counts.get(task["status"], 0) + 1
    open_now = counts.get("open", 0) + counts.get("in_progress", 0)
    mvp_open = sum(1 for t in tasks
                   if t["priority"] == "mvp" and t["status"] in ("open", "in_progress"))

    def options(values, labels=None):
        return "".join(
            f'<option value="{v}">{(labels or {}).get(v, v)}</option>'
            for v in values
        )

    priorities = [p for p in PRIORITY_ORDER if any(t["priority"] == p for t in tasks)]
    statuses = sorted({t["status"] for t in tasks})
    areas = sorted({t["area"] for t in tasks})

    summary = (
        f"{len(tasks)} tasks · {open_now} open · {mvp_open} open at MVP priority · "
        f"generated from backlog.json, last updated {meta.get('last_updated', '?')} · "
        f"never edit this file"
    )
    return (HTML_TEMPLATE
            .replace("__META__", summary)
            .replace("__PRIORITIES__", options(priorities))
            .replace("__STATUSES__", options(statuses))
            .replace("__AREAS__", options(areas, AREA_LABEL))
            .replace("__DATA__", json.dumps(tasks, ensure_ascii=False)))


def recompute_metadata(data: dict) -> list[str]:
    """Derive `total_tasks` and `next_id` from the tasks themselves.

    They were maintained by hand and drifted: on 2026-09-10 the file said 244
    tasks and `TASK-245` next while actually holding 258. A stored count that
    disagrees with the array is worse than no count, because the next id is read
    from it — and reusing an id silently reattributes work to a task somebody
    else has already referred to.

    So nothing trusts the stored values: they are recomputed here and written
    back, and the protocol tells the assistant to take the next id from the array
    rather than from the field. Returns a list of the corrections made, so a
    drift is reported rather than fixed in silence.
    """
    meta = data["metadata"]
    tasks = data["tasks"]
    corrections: list[str] = []

    total = len(tasks)
    if meta.get("total_tasks") != total:
        corrections.append(f"total_tasks {meta.get('total_tasks')} → {total}")
        meta["total_tasks"] = total

    # The highest id ever used, plus one. Highest rather than count, because ids
    # are never reused and a dropped task still holds its number.
    highest = 0
    for task in tasks:
        try:
            highest = max(highest, int(str(task["id"]).split("-")[-1]))
        except (ValueError, KeyError):
            continue
    next_id = f"TASK-{highest + 1:03d}"
    if meta.get("next_id") != next_id:
        corrections.append(f"next_id {meta.get('next_id')} → {next_id}")
        meta["next_id"] = next_id

    return corrections


def main() -> int:
    if not SOURCE.exists():
        print(f"error: {SOURCE} not found", file=sys.stderr)
        return 1
    data = json.loads(SOURCE.read_text(encoding="utf-8"))

    ids = [t["id"] for t in data["tasks"]]
    if len(ids) != len(set(ids)):
        print("error: duplicate task IDs in backlog.json", file=sys.stderr)
        return 1

    corrections = recompute_metadata(data)
    if corrections:
        SOURCE.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n",
                          encoding="utf-8")
        for line in corrections:
            print(f"corrected metadata: {line}")

    HTML_TARGET.write_text(render_html(data), encoding="utf-8")
    written = [HTML_TARGET]
    if "--md" in sys.argv[1:] or TARGET.exists():
        TARGET.write_text(render(data), encoding="utf-8")
        written.append(TARGET)
    print(f"wrote {' and '.join(str(p.relative_to(REPO)) for p in written)} "
          f"({len(data['tasks'])} tasks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
