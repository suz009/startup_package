#!/usr/bin/env python3
"""Regenerate BACKLOG.html (and, on request, BACKLOG.md) from backlog.json.

INSTALL: replace every `[PROJECT_NAME]` in this file with the project's name,
and replace `AREA_LABEL` below with the project's own area vocabulary.

`backlog.json` is the canonical list; the views are generated from it and are
never edited by hand. They are regenerated by the pre-commit hook whenever the
JSON is staged, so a stale view cannot reach a commit — which is the only sense
in which "kept in sync" can be made to mean something.

**BACKLOG.html is the default view** (user's instruction, 2026-09-25): one row
per task, sortable by any column, filterable by priority, status, area and period-work fit, and
searchable across the title and the description. It carries the whole of
`backlog.json` inside it, so it is one self-contained file that opens from disk
with no server and no network. Open it in a browser.

**BACKLOG.md** is optional (`--md`): a document grouped by priority, for reading
in order or in a diff. If a repo already has a BACKLOG.md, it keeps being
regenerated so it cannot go stale.

It also **recomputes `metadata.total_tasks` and `metadata.next_id`** from the
tasks themselves and writes the correction back. Those fields were maintained by
hand and drifted; see `recompute_metadata`.

Standard library only. See 0_context/protocol/BACKLOG_PROTOCOL.md.

Usage:
    python3 scripts/render_backlog.py          # BACKLOG.html (+ BACKLOG.md if it exists)
    python3 scripts/render_backlog.py --md     # also create/refresh BACKLOG.md
"""

from __future__ import annotations

import json
